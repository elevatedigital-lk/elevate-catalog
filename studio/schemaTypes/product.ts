import {defineField, defineType} from 'sanity'

export default defineType({
  name: 'product',
  title: 'Product',
  type: 'document',
  fields: [
    defineField({
      name: 'name',
      title: 'Product Name (English)',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'nameSi',
      title: 'Product Name (Sinhala)',
      type: 'string',
      description: 'Optional. Shown when a customer views the site in Sinhala. Falls back to the English name if left blank.',
    }),
    defineField({
      name: 'slug',
      title: 'URL Slug',
      type: 'slug',
      description: 'Used in the product page link. Click "Generate" to create it from the product name.',
      options: {source: 'name', maxLength: 96},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'code',
      title: 'Product Code',
      type: 'string',
      description: 'Short code customers will quote on WhatsApp, e.g. BT-101',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'price',
      title: 'Price (LKR)',
      type: 'number',
      validation: (Rule) => Rule.required().min(0),
    }),
    defineField({
      name: 'images',
      title: 'Product Images',
      type: 'array',
      of: [{type: 'image', options: {hotspot: true}}],
      validation: (Rule) => Rule.required().min(1).max(5).error('Add between 1 and 5 images'),
    }),
    defineField({
      name: 'inStock',
      title: 'In Stock',
      type: 'boolean',
      initialValue: true,
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'reference',
      to: [{type: 'category'}],
      description: 'Men / Women / Kids — add new categories under "Category" in the sidebar.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'productType',
      title: 'Type',
      type: 'reference',
      to: [{type: 'productType'}],
      description: 'Casual / Office / Sports etc. — add new types under "Type" in the sidebar.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'description',
      title: 'Description (English)',
      type: 'text',
      rows: 4,
      description: 'Optional. More detail shown on the product\'s own page (material, fit, etc.).',
    }),
    defineField({
      name: 'descriptionSi',
      title: 'Description (Sinhala)',
      type: 'text',
      rows: 4,
      description: 'Optional. Falls back to the English description if left blank.',
    }),
    defineField({
      name: 'availableSizes',
      title: 'Available Sizes',
      type: 'string',
      description: 'Optional. Comma-separated, e.g. 38, 39, 40, 41, 42, 43, 44',
    }),
    defineField({
      name: 'sizeChartImage',
      title: 'Size Chart Image',
      type: 'image',
      description: 'Optional. Upload a size chart photo/diagram to show on the product page.',
    }),
    defineField({
      name: 'order',
      title: 'Display Order',
      type: 'number',
      description: 'Lower numbers show first. Optional.',
    }),
  ],
  preview: {
    select: {
      title: 'name',
      subtitle: 'code',
      media: 'images.0',
    },
  },
})
